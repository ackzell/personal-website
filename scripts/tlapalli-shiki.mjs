/**
 * Copies the tlapalli VS Code themes into shiki/tlapalli.json, keeping only
 * what Shiki reads: the token rules and the editor's own background and
 * foreground. Also writes app/assets/css/tlapalli.css, which colors code in
 * the gem a block asks for, in the page's scheme, and selects it in the
 * gem's own selection color. Run it again after a theme release:
 *
 *   node scripts/tlapalli-shiki.mjs ../oss/tlapalli-vscode-theme/themes
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) throw new Error('Usage: node scripts/tlapalli-shiki.mjs <themes dir>')

const DEFAULT_GEM = 'jade'

const themes = readdirSync(dir)
  .filter((file) => /^tlapalli-.+-theme\.json$/.test(file))
  .sort()
  .map((file) => {
    const theme = JSON.parse(readFileSync(join(dir, file), 'utf8'))
    // tlapalli-fire-opal-light-theme.json -> tlapalli-fire-opal-light
    const name = file.replace(/-theme\.json$/, '')
    return {
      name,
      displayName: theme.name,
      type: theme.type,
      colors: {
        'editor.background': theme.colors['editor.background'],
        'editor.foreground': theme.colors['editor.foreground'],
        'editor.selectionBackground': theme.colors['editor.selectionBackground'],
      },
      // TextMate's shape (what Content's config types ask for): the editor's
      // colors first, then the token rules.
      settings: [
        { settings: { foreground: theme.colors['editor.foreground'], background: theme.colors['editor.background'] } },
        ...theme.tokenColors,
      ],
    }
  })

writeFileSync(new URL('../shiki/tlapalli.json', import.meta.url), `${JSON.stringify(themes, null, 2)}\n`)

// Shiki keys each theme by its name without the prefix (nuxt.config.ts), so a
// token carries --shiki-jade, --shiki-jade-light, and so on.
const key = (theme) => theme.name.replace('tlapalli-', '')
const gems = themes.filter((theme) => theme.type === 'dark').map(key)
const byKey = new Map(themes.map((theme) => [key(theme), theme]))

const schemes = [
  { root: ':root.dark', suffix: '' },
  { root: ':root:not(.dark)', suffix: '-light' },
]

function rules(scope, gem) {
  return schemes.map(({ root, suffix }) => {
    const theme = byKey.get(gem + suffix)
    const v = `--shiki-${gem}${suffix}`
    const at = [root, scope].filter(Boolean).join(' ')
    // Only the gem's text color: code sits on the stage, never on the
    // editor's own background (The Stage Rule, DESIGN.md).
    return `${at} {
  --code-fg: ${theme.colors['editor.foreground']};
  --code-selection: ${theme.colors['editor.selectionBackground']};
}
${at} .shiki span {
  color: var(${v});
  font-style: var(${v}-font-style);
}`
  }).join('\n')
}

const css = `/* Generated by scripts/tlapalli-shiki.mjs from the tlapalli themes. Don't edit. */

/* Code anywhere is jade, unless a block names another gem (data-gem). */
${rules('', DEFAULT_GEM)}

/* Selected code keeps its colors over the gem's selection, as in the editor. */
.shiki ::selection {
  background-color: var(--code-selection);
}

${gems.map((gem) => rules(`[data-gem='${gem}']`, gem)).join('\n\n')}
`

writeFileSync(new URL('../app/assets/css/tlapalli.css', import.meta.url), css)
console.log(`${themes.length} themes, ${gems.length} gems written`)
